"""Integration tests against versioned, real OpenSSL TLS 1.3 PCAP fixtures."""

from __future__ import annotations

import hashlib
import json
import os
import shutil
import subprocess
from pathlib import Path

import pytest

from pqtls.pcap import analyze_pcap

FIXTURE_DIR = Path(__file__).parent / "fixtures" / "pcap"
MANIFEST_PATH = FIXTURE_DIR / "manifest.json"
pytestmark = pytest.mark.skipif(
    not MANIFEST_PATH.is_file(),
    reason="Real TLS PCAP fixtures are generated by the dedicated fixture workflow.",
)


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _load_manifest() -> dict:
    return json.loads(MANIFEST_PATH.read_text(encoding="utf-8"))


def _tshark_fields(
    capture: Path,
    keylog: Path,
    fields: list[str],
    display_filter: str | None = None,
) -> list[list[str]]:
    command = [
        shutil.which("tshark") or "tshark",
        "-r",
        str(capture),
        "-o",
        f"tls.keylog_file:{keylog}",
        "-T",
        "fields",
        "-E",
        "header=n",
        "-E",
        "separator=\t",
        "-E",
        "occurrence=a",
        "-E",
        "aggregator=,",
    ]
    if display_filter:
        command.extend(["-Y", display_filter])
    for field in fields:
        command.extend(["-e", field])
    result = subprocess.run(command, capture_output=True, text=True, check=False, timeout=60)
    assert result.returncode == 0, result.stderr
    return [
        line.split("\t")
        for line in result.stdout.splitlines()
        if line
    ]


def _as_ints(value: str) -> list[int]:
    parsed: list[int] = []
    for item in value.split(","):
        try:
            parsed.append(int(item, 0))
        except ValueError:
            continue
    return parsed


def _independent_directional_totals(
    capture: Path, keylog: Path
) -> tuple[dict[str, dict[str, int]], float, float, float]:
    event_rows = _tshark_fields(
        capture,
        keylog,
        ["frame.time_epoch", "ip.src", "tcp.srcport", "tls.handshake.type"],
        "tls.handshake.type == 1 || tls.handshake.type == 20",
    )
    client_hello: float | None = None
    server_finished: float | None = None
    client_finished: float | None = None
    client_endpoint: tuple[str, str] | None = None
    for row in event_rows:
        if len(row) < 4:
            continue
        try:
            timestamp = float(row[0])
        except ValueError:
            continue
        source = row[1]
        source_port = row[2]
        event_types = _as_ints(row[3])
        if 1 in event_types and client_hello is None:
            client_hello = timestamp
            client_endpoint = (source, source_port)
        if 20 in event_types and client_endpoint is not None:
            if (source, source_port) == client_endpoint and client_finished is None:
                client_finished = timestamp
            elif (source, source_port) != client_endpoint and server_finished is None:
                server_finished = timestamp

    assert client_hello is not None
    assert server_finished is not None
    assert client_finished is not None

    packet_rows = _tshark_fields(
        capture,
        keylog,
        [
            "tcp.stream",
            "ip.src",
            "ip.dst",
            "tcp.srcport",
            "tcp.dstport",
            "tcp.seq",
            "tcp.len",
            "ip.len",
        ],
    )
    totals: dict[str, dict[str, int]] = {}
    unique_sequences: dict[str, set[int]] = {}
    for row in packet_rows:
        if len(row) < 8 or not row[0] or not row[1] or not row[3] or not row[4]:
            continue
        stream_id = int(row[0], 0)
        source_endpoint = (row[1], row[3])
        destination_endpoint = (row[2], row[4])
        if source_endpoint == client_endpoint:
            direction = "client_to_server"
        elif destination_endpoint == client_endpoint:
            direction = "server_to_client"
        else:
            continue
        label = f"stream_{stream_id}_{direction}"
        current = totals.setdefault(
            label,
            {
                "ip_bytes_including_retransmissions": 0,
                "tcp_payload_captured_bytes": 0,
                "tcp_payload_unique_bytes": 0,
            },
        )
        current["ip_bytes_including_retransmissions"] += sum(_as_ints(row[7]))
        sequence_values = _as_ints(row[5])
        payload_lengths = _as_ints(row[6])
        if sequence_values and payload_lengths:
            sequence = sequence_values[0]
            payload_length = sum(payload_lengths)
            current["tcp_payload_captured_bytes"] += payload_length
            covered = unique_sequences.setdefault(label, set())
            before = len(covered)
            covered.update(range(sequence, sequence + payload_length))
            current["tcp_payload_unique_bytes"] += len(covered) - before
    return totals, client_hello, server_finished, client_finished


@pytest.mark.parametrize(
    ("fixture_name", "expected_group", "expected_kind"),
    [
        ("hybrid-full", "X25519MLKEM768", "full"),
        ("classical-full", "X25519", "full"),
        ("hybrid-resumed", "X25519MLKEM768", "resumed"),
    ],
)
def test_real_tls13_fixture_measurements(
    fixture_name: str, expected_group: str, expected_kind: str
) -> None:
    entry = next(item for item in _load_manifest()["fixtures"] if item["name"] == fixture_name)
    capture = FIXTURE_DIR / entry["pcap_file"]
    keylog = FIXTURE_DIR / entry["keylog_file"]
    endpoint_log = FIXTURE_DIR / entry["endpoint_log_file"]

    assert _sha256(capture) == entry["capture_sha256"]
    assert _sha256(keylog) == entry["keylog_sha256"]
    assert _sha256(endpoint_log) == entry["endpoint_log_sha256"]
    os.chmod(keylog, 0o600)

    result = analyze_pcap(
        capture,
        keylog_path=keylog,
        endpoint_session_reused=entry["endpoint_session_reused"],
    )
    assert result["packet_count"] > 0
    assert result["session_kind"] == expected_kind
    assert result["session_kind_evidence"] in {
        "pcap_handshake_messages",
        "pcap_psk_selection_plus_endpoint_session_reuse_confirmation",
    }
    assert {"client_hello", "server_hello", "finished"}.issubset(
        set(result["handshake_events_observed"])
    )
    if expected_kind == "full":
        assert "certificate" in result["handshake_events_observed"]
        assert "certificate_verify" in result["handshake_events_observed"]
        assert result["negotiated_group"] == expected_group
    else:
        assert result["psk_selected_identity_observed"] is True
        assert "certificate" not in result["handshake_events_observed"]
        assert "certificate_verify" not in result["handshake_events_observed"]

    assert result["clienthello_to_server_finished_ms"] is not None
    assert result["clienthello_to_client_finished_ms"] is not None
    assert result["clienthello_to_server_finished_ms"] >= 0
    assert result["clienthello_to_client_finished_ms"] >= 0

    metrics = {item["name"]: item for item in result["metrics"]}
    for metric in metrics.values():
        if metric["value"] is None:
            assert metric["label"] == "Not measured"
            assert metric["not_measured_reason"]
            assert metric["source"] is None
        else:
            assert metric["label"] == "Measured"
            assert metric["source"]

    assert metrics["tcp_ip_bytes"]["value"] > 0
    assert metrics["tcp_payload_unique_bytes"]["value"] > 0
    assert metrics["tls_record_bytes"]["value"] > 0
    assert metrics["handshake_message_bytes"]["value"] > 0
    assert metrics["clienthello_to_server_finished_ms"]["value"] is not None
    assert metrics["clienthello_to_client_finished_ms"]["value"] is not None

    independent, hello, server_finished, client_finished = _independent_directional_totals(
        capture, keylog
    )
    assert result["tcp_directional_accounting"] == independent
    assert result["clienthello_to_server_finished_ms"] == pytest.approx(
        (server_finished - hello) * 1000, abs=0.01
    )
    assert result["clienthello_to_client_finished_ms"] == pytest.approx(
        (client_finished - hello) * 1000, abs=0.01
    )
    assert metrics["tcp_ip_bytes"]["value"] == sum(
        item["ip_bytes_including_retransmissions"] for item in independent.values()
    )
    assert metrics["tcp_payload_unique_bytes"]["value"] == sum(
        item["tcp_payload_unique_bytes"] for item in independent.values()
    )


def test_psk_capture_without_endpoint_reuse_evidence_stays_unknown() -> None:
    entry = next(
        item for item in _load_manifest()["fixtures"] if item["name"] == "hybrid-resumed"
    )
    capture = FIXTURE_DIR / entry["pcap_file"]
    keylog = FIXTURE_DIR / entry["keylog_file"]
    os.chmod(keylog, 0o600)

    result = analyze_pcap(capture, keylog_path=keylog)

    assert result["psk_selected_identity_observed"] is True
    assert result["session_kind"] == "unknown"
    assert "endpoint session-reuse confirmation" in result["session_kind_reason"]
